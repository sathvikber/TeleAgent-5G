"""
task.py

Represents a single unit of work generated by the Task Planner.

A user query may produce one or more tasks. Each task is
independently dispatched to the appropriate specialized agent.

Author : TeleAgent-5G
Version : 0.2
"""

from dataclasses import dataclass, field
from typing import Any


@dataclass(frozen=True, slots=True)
class Task:
    """
    Represents an executable task.

    Parameters
    ----------
    task_id : str
        Unique identifier of the task.

    intent : str
        Target intent (e.g., "network", "log",
        "monitoring", "knowledge").

    query : str
        User query or sub-query assigned to
        this task.

    metadata : dict[str, Any]
        Optional task metadata.
    """

    task_id: str

    intent: str

    query: str

    metadata: dict[str, Any] = field(default_factory=dict)
