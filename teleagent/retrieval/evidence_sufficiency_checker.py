"""
Evidence Sufficiency Checker

Determines whether retrieved evidence actually contains the
information required by the user's query.

The first implementation focuses on definition queries because
these were shown to produce semantic drift such as:

Question:
    "What is UDM?"

Retrieved evidence:
    "Services provided by UDM..."

Incorrect model behavior:
    answering with UDM services instead of a definition.

This component prevents the SLM from being called when explicit
definition evidence is absent.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from typing import Optional

from teleagent.retrieval.query_type_detector import QueryAnalysis


@dataclass(frozen=True)
class EvidenceSufficiencyResult:
    """
    Result of deterministic evidence validation.

    Attributes
    ----------
    is_sufficient : bool
        Whether the evidence is sufficient for the detected
        query type.

    reason : str
        Human-readable diagnostic reason.

    matched_evidence : Optional[str]
        Definition or evidence fragment that satisfied the check.
    """

    is_sufficient: bool
    reason: str
    matched_evidence: Optional[str] = None


class EvidenceSufficiencyChecker:
    """
    Checks whether retrieved RAG evidence is appropriate for
    the user's information need.
    """

    FALLBACK_RESPONSE = (
        "The information is not available in the current knowledge base."
    )

    # ---------------------------------------------------------
    # Public API
    # ---------------------------------------------------------

    def check(
        self,
        analysis: QueryAnalysis,
        evidence: str,
    ) -> EvidenceSufficiencyResult:
        """
        Evaluate evidence sufficiency.

        Parameters
        ----------
        analysis : QueryAnalysis
            Structured query interpretation.

        evidence : str
            Compact evidence generated by the retrieval pipeline.

        Returns
        -------
        EvidenceSufficiencyResult
            Sufficiency decision.
        """

        evidence = (evidence or "").strip()

        if not evidence:
            return EvidenceSufficiencyResult(
                is_sufficient=False,
                reason="No evidence was retrieved.",
            )

        # -----------------------------------------------------
        # Definition queries
        # -----------------------------------------------------

        if analysis.query_type == "definition":

            return self._check_definition(
                target=analysis.target_entity,
                evidence=evidence,
            )

        # -----------------------------------------------------
        # Other query types
        #
        # Do not introduce aggressive gating yet.
        # These can be added incrementally after definition
        # queries are validated.
        # -----------------------------------------------------

        return EvidenceSufficiencyResult(
            is_sufficient=True,
            reason=(
                f"No strict sufficiency gate is currently enabled "
                f"for query type '{analysis.query_type}'."
            ),
        )

    # ---------------------------------------------------------
    # Definition validation
    # ---------------------------------------------------------

    def _check_definition(
        self,
        target: Optional[str],
        evidence: str,
    ) -> EvidenceSufficiencyResult:
        """
        Check whether evidence explicitly defines the target.
        """

        if not target:
            return EvidenceSufficiencyResult(
                is_sufficient=False,
                reason=(
                    "Definition query detected but target entity "
                    "could not be identified."
                ),
            )

        # -----------------------------------------------------
        # First preference:
        # canonical definition section generated by TeleAgent
        # -----------------------------------------------------

        canonical_section = self._extract_canonical_definition_section(
            evidence
        )

        if canonical_section:

            match = self._find_explicit_definition(
                target,
                canonical_section,
            )

            if match:
                return EvidenceSufficiencyResult(
                    is_sufficient=True,
                    reason=(
                        f"Explicit canonical definition found "
                        f"for {target}."
                    ),
                    matched_evidence=match,
                )

        # -----------------------------------------------------
        # Second preference:
        # inspect complete compact evidence for an explicit
        # definition pattern.
        # -----------------------------------------------------

        match = self._find_explicit_definition(
            target,
            evidence,
        )

        if match:
            return EvidenceSufficiencyResult(
                is_sufficient=True,
                reason=(
                    f"Explicit definition evidence found for "
                    f"{target}."
                ),
                matched_evidence=match,
            )

        # -----------------------------------------------------
        # No explicit definition
        # -----------------------------------------------------

        return EvidenceSufficiencyResult(
            is_sufficient=False,
            reason=(
                f"Retrieved evidence mentions {target} but does "
                f"not explicitly define it."
            ),
        )

    # ---------------------------------------------------------
    # Canonical definition section
    # ---------------------------------------------------------

    @staticmethod
    def _extract_canonical_definition_section(
        evidence: str,
    ) -> Optional[str]:
        """
        Extract the compact-evidence canonical definition block.

        Expected heading:

        CANONICAL DEFINITIONS FOUND IN DEFINITION SECTIONS
        """

        heading = (
            "CANONICAL DEFINITIONS FOUND IN DEFINITION SECTIONS"
        )

        upper_evidence = evidence.upper()
        index = upper_evidence.find(heading)

        if index < 0:
            return None

        start = index + len(heading)
        remaining = evidence[start:]

        lines = remaining.splitlines()

        collected = []

        for line in lines:

            stripped = line.strip()

            if not stripped:
                if collected:
                    continue

                continue

            # Stop when another compact-evidence heading begins.
            if (
                stripped.isupper()
                and len(stripped) > 8
                and ":" not in stripped
            ):
                break

            collected.append(line)

        if not collected:
            return None

        return "\n".join(collected).strip()

    # ---------------------------------------------------------
    # Definition matching
    # ---------------------------------------------------------

    def _find_explicit_definition(
        self,
        target: str,
        text: str,
    ) -> Optional[str]:
        """
        Find an explicit definition of the requested target.

        Accepted examples:

            AUSF: AUthentication Server Function

            AUthentication Server Function (AUSF)

            AUSF stands for AUthentication Server Function

            AUSF means AUthentication Server Function

            AUSF is a network function ...

        The patterns deliberately do NOT treat:

            "services provided by AUSF"

        or

            "AUSF provides ..."

        as definitions.
        """

        escaped = re.escape(target)

        patterns = [

            # -------------------------------------------------
            # AUSF: AUthentication Server Function
            # -------------------------------------------------
            re.compile(
                rf"(?im)^\s*{escaped}\s*:\s*"
                rf"(?P<definition>[^\n]{{3,250}})$"
            ),

            # -------------------------------------------------
            # AUthentication Server Function (AUSF)
            # -------------------------------------------------
            re.compile(
                rf"(?im)^\s*"
                rf"(?P<definition>[A-Za-z][A-Za-z0-9 ,/\-]{{3,200}})"
                rf"\s*\(\s*{escaped}\s*\)"
            ),

            # -------------------------------------------------
            # AUSF stands for ...
            # AUSF means ...
            # -------------------------------------------------
            re.compile(
                rf"(?im)\b{escaped}\b\s+"
                rf"(?:stands\s+for|means)\s+"
                rf"(?P<definition>[^\n.;]{{3,250}})"
            ),

            # -------------------------------------------------
            # AUSF is a/an/the ...
            #
            # Allows a directly stated entity definition but
            # does not accept generic "AUSF provides..." text.
            # -------------------------------------------------
            re.compile(
                rf"(?im)\b{escaped}\b\s+is\s+"
                rf"(?:a|an|the)\s+"
                rf"(?P<definition>[^\n.;]{{3,250}})"
            ),
        ]

        for pattern in patterns:

            match = pattern.search(text)

            if not match:
                continue

            full_match = match.group(0).strip()

            # Defensive rejection of service-list headings.
            lower = full_match.lower()

            if lower.startswith("services provided by"):
                continue

            return full_match

        return None
